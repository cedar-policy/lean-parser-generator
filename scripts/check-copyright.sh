# Check that source files carry the Cedar copyright notice.
#
#   scripts/check-copyright.sh           check files staged for commit
#   scripts/check-copyright.sh --all     check every tracked or untracked, non-ignored file
#   scripts/check-copyright.sh --fix ... add the notice to files that lack it
#
# Checked extensions: .lean .py .sh .js. The notice must appear in the first 5
# lines (so a shebang line may come first). Generated files (a `-- Generated by`
# comment in the first 5 lines) are skipped.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

mode=staged
fix=0
for arg in "$@"; do
  case "$arg" in
    --all) mode=all ;;
    --fix) fix=1 ;;
    *) echo "usage: $0 [--all] [--fix]" >&2; exit 64 ;;
  esac
done

if [ "$mode" = all ]; then
  files=$(git ls-files --cached --others --exclude-standard)
else
  files=$(git diff --cached --name-only --diff-filter=ACM)
fi

license_lines=(
  "Copyright Cedar Contributors"
  ""
  'Licensed under the Apache License, Version 2.0 (the "License");'
  "you may not use this file except in compliance with the License."
  "You may obtain a copy of the License at"
  ""
  "     https://www.apache.org/licenses/LICENSE-2.0"
  ""
  "Unless required by applicable law or agreed to in writing, software"
  'distributed under the License is distributed on an "AS IS" BASIS,'
  "WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied."
  "See the License for the specific language governing permissions and"
  "limitations under the License."
)

# Print the notice in the comment syntax of extension $1.
notice() {
  case "$1" in
    lean)
      echo "/-"
      for l in "${license_lines[@]}"; do [ -z "$l" ] && echo "" || echo " $l"; done
      echo "-/"
      ;;
    py|sh|js)
      local p="#"; [ "$1" = js ] && p="//"
      for l in "${license_lines[@]}"; do [ -z "$l" ] && echo "$p" || echo "$p $l"; done
      ;;
  esac
}

missing=()
for f in $files; do
  [ -f "$f" ] || continue
  case "$f" in
    *node_modules/*) continue ;;
    *.lean) ext=lean ;;
    *.py) ext=py ;;
    *.sh) ext=sh ;;
    *.js) ext=js ;;
    *) continue ;;
  esac
  if head -n 5 "$f" | grep -q "Copyright Cedar Contributors"; then continue; fi
  # Generated files are produced by the tool and carry no notice.
  if head -n 5 "$f" | grep -q '^-- Generated by'; then continue; fi
  if [ "$fix" = 1 ]; then
    tmp=$(mktemp)
    if head -n 1 "$f" | grep -q '^#!'; then
      { head -n 1 "$f"; notice "$ext"; tail -n +2 "$f"; } > "$tmp"
    else
      { notice "$ext"; echo; cat "$f"; } > "$tmp"
    fi
    cat "$tmp" > "$f"; rm -f "$tmp"
    echo "added notice: $f"
  else
    missing+=("$f")
  fi
done

if [ "${#missing[@]}" -gt 0 ]; then
  echo "Missing 'Copyright Cedar Contributors' notice in:" >&2
  printf '  %s\n' "${missing[@]}" >&2
  echo "Run scripts/check-copyright.sh --fix (add --all for every file)." >&2
  exit 1
fi
